function parkedCodes(snapshot: GraftSnapshot): Record<string, string> {
  const out: Record<string, string> = {};
  for (const p of snapshot.parked) out[p.agentId] = p.code;
  return out;
}

function graftedAgentIds(snapshot: GraftSnapshot): string[] {
  return agentNodes(snapshot.root)
    .filter((n) => n.id !== ROOT_NODE_ID)
    .map((n) => n.id)
    .sort();
}

function childAgentIds(node: AgentNode): string[] {
  return node.children
    .filter((c): c is AgentNode => isAgentNode(c))
    .map((c) => c.id)
    .sort();
}

async function fileDigests(root: string): Promise<Record<string, string>> {
  const out: Record<string, string> = {};
  const visit = async (dir: string): Promise<void> => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        await visit(full);
        continue;
      }
      out[full.slice(root.length + 1).split('\\').join('/')] = createHash('sha256')
        .update(await readFile(full))
        .digest('hex');
    }
  };
  await visit(root);
  return out;
}

