describe('captured sessions graft to their committed golden snapshots', () => {
  it('every session transcript in the captured slug has a golden and matches it', async () => {
    const sessionIds = await capturedSessionIds();
    // Derived, not pinned: a re-harvest adds sessions rather than failing here.
    expect(sessionIds.length).toBeGreaterThan(0);

    for (const sessionId of sessionIds) {
      const result = await graftSession(join(CAPTURED_SLUG, `${sessionId}.jsonl`));
      if (!result.ok) throw new Error(`captured session ${sessionId} refused: ${result.mismatch.code}`);
      const produced = goldenText(result.snapshot);
      const goldenPath = join(GOLDEN_DIR, `${sessionId}.json`);
      if (UPDATE_GOLDENS) {
        await writeFile(goldenPath, produced, 'utf8');
        continue;
      }
      const committed = await readFile(goldenPath, 'utf8');
      expect(committed.split('\r\n').join('\n'), `golden mismatch for ${sessionId}`).toBe(produced);
    }
  });

  it('the golden directory holds exactly one golden per captured session', async () => {
    if (UPDATE_GOLDENS) return;
    const sessionIds = await capturedSessionIds();
    const goldens = (await readdir(GOLDEN_DIR))
      .filter((n) => n.endsWith('.json'))
      .map((n) => n.replace(/\.json$/, ''))
      .sort();
    expect(goldens).toEqual(sessionIds);
  });

  it('a golden is stable across repeated grafts of the same input', async () => {
    const main = join(CAPTURED_SLUG, `${(await capturedSessionIds())[0] as string}.jsonl`);
    const a = await graftSession(main);
    const b = await graftSession(main);
    if (!a.ok || !b.ok) throw new Error('captured session must graft');
    expect(goldenText(a.snapshot)).toBe(goldenText(b.snapshot));
  });

  it('grafting the captured tree leaves every fixture byte-identical (G1)', async () => {
    const before = await fileDigests(CAPTURED_ROOT);
    for (const sessionId of await capturedSessionIds()) {
      await graftSession(join(CAPTURED_SLUG, `${sessionId}.jsonl`));
    }
    expect(await fileDigests(CAPTURED_ROOT)).toEqual(before);
  });

  it('a manual in-order replay reproduces graftSession exactly', async () => {
    for (const sessionId of await capturedSessionIds()) {
      const main = join(CAPTURED_SLUG, `${sessionId}.jsonl`);
      const loaded = await graftSession(main);
      if (!loaded.ok) throw new Error('captured session must graft');
      const session = await loadReplay(main);
      const manual = replay(session, inOrderScript(session));
      expect(goldenText(manual), sessionId).toBe(goldenText(loaded.snapshot));
    }
  });
});

