describe('snapshots are immutable and machine-independent', () => {
  it('a snapshot is deep-frozen', async () => {
    const result = await graftSession(graftMain('00-valid-control'));
    if (!result.ok) throw new Error('must graft');
    expect(Object.isFrozen(result.snapshot)).toBe(true);
    expect(Object.isFrozen(result.snapshot.root)).toBe(true);
    expect(Object.isFrozen(result.snapshot.root.children)).toBe(true);
    walk(result.snapshot.root, (node) => expect(Object.isFrozen(node)).toBe(true));
  });

  it('two snapshots from one grafter share no node objects', async () => {
    const session = await loadReplay(graftMain('00-valid-control'));
    const grafter = newGrafter(session);
    for (const step of inOrderScript(session)) apply(grafter, session, step);
    const a = grafter.snapshot();
    const b = grafter.snapshot();
    expect(a).not.toBe(b);
    expect(a.root).not.toBe(b.root);
    expect(goldenText(a)).toBe(goldenText(b));
  });

  it('the serialized form contains no absolute path and no wall-clock value', async () => {
    for (const sessionId of await capturedSessionIds()) {
      const result = await graftSession(join(CAPTURED_SLUG, `${sessionId}.jsonl`));
      if (!result.ok) throw new Error('must graft');
      const text = goldenText(result.snapshot);
      // No drive letters, no UNC prefixes, no POSIX home paths.
      expect(/[A-Za-z]:[\\/]/.test(text)).toBe(false);
      expect(text.includes('\\\\')).toBe(false);
      expect(text.includes('/home/')).toBe(false);
      expect(text.includes('/Users/')).toBe(false);
      expect(text.toLowerCase().includes('.claude')).toBe(false);
      // The only absolute time in the file is the anchor, taken from a fixture
      // line. Everything else is an offset.
      const parsed = JSON.parse(text) as { epochAnchor: string | null };
      expect(parsed.epochAnchor).toBeTruthy();
      expect(Date.parse(parsed.epochAnchor as string)).toBeLessThan(Date.now());
      const isoCount = text.match(/\d{4}-\d{2}-\d{2}T/g) ?? [];
      expect(isoCount).toHaveLength(1);
    }
  });

  it('serializeSnapshot pins previews by digest, not verbatim', async () => {
    const session = await sessionWhere(
      'at least one `tool_use` block, so there is a preview to pin',
      (candidate) => candidate.toolUseIds.length > 0,
    );
    const result = await graftSession(session.mainTranscript);
    if (!result.ok) throw new Error(`must graft: ${result.mismatch.code}`);
    const serialized = serializeSnapshot(result.snapshot);
    const previews: unknown[] = [];
    const collect = (node: Record<string, unknown>): void => {
      if (node['node'] === 'tool') previews.push(node['inputPreview']);
      const children = node['children'];
      if (Array.isArray(children)) for (const c of children) collect(c as Record<string, unknown>);
    };
    collect(serialized.root as unknown as Record<string, unknown>);
    expect(previews.length).toBeGreaterThan(0);
    for (const p of previews) expect(String(p)).toMatch(/^sha256:[0-9a-f]{16}:\d+$/);
  });

  it('toSessionState takes liveness as an argument rather than inventing one', async () => {
    const result = await graftSession(graftMain('00-valid-control'));
    if (!result.ok) throw new Error('must graft');
    const state = toSessionState(result.snapshot, { liveness: 'idle', workspaceMatch: true });
    expect(state.liveness).toBe('idle');
    expect(state.schemaOk).toBe(true);
    expect(state.root).toBe(result.snapshot.root);
    expect(state.sessionId).toBe(result.snapshot.sessionId);
  });
});

